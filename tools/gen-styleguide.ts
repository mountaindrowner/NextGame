// ------------------------------------------------------------- tile strip
const tile = (set: (x: number, y: number, c: [number, number, number, number]) => void, ox: number, base: string[], speckle: string[], density: number, seed: number): void => {
  const rng = new Rng(seed);
  for (let y = 0; y < 16; y++)
    for (let x = 0; x < 16; x++) set(ox + x, y, hex(base[(x + y) % base.length] ?? 'ffffff'));
  for (let i = 0; i < density; i++) {
    set(ox + rng.int(0, 15), rng.int(0, 15), hex(speckle[rng.int(0, speckle.length - 1)] ?? 'ffffff'));
  }
};

