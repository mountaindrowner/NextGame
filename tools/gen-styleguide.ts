function writePng(name: string, width: number, height: number, paint: (set: (x: number, y: number, c: [number, number, number, number]) => void) => void, prompt: string): void {
  const png = new PNG({ width, height });
  const set = (x: number, y: number, c: [number, number, number, number]): void => {
    if (x < 0 || y < 0 || x >= width || y >= height) return;
    const i = (y * width + x) * 4;
    png.data[i] = c[0];
    png.data[i + 1] = c[1];
    png.data[i + 2] = c[2];
    png.data[i + 3] = c[3];
  };
  paint(set);
  writeFileSync(join(OUT, `${name}.png`), PNG.sync.write(png));
  writeFileSync(
    join(OUT, `${name}.prompt.txt`),
    `OHMFRONT style-guide asset "${name}"\nGenerated by: tools/gen-styleguide.ts (npm run gen:styleguide)\nAuthor: Claude (hand-placed pixel grids / deterministic procedure)\nRules: docs/style-guide.md — Gen 3 GBA, <=16 colors incl. transparency,\n240x160 presentation, light from top-left, dark outline with sel-out.\n${prompt}\n`,
  );
  console.log(`wrote ${name}.png (${width}x${height})`);
}

function sprite(name: string, rows: string[], palette: Palette, canvas: number, prompt: string): void {
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  if (w > canvas || h > canvas) throw new Error(`${name} ${w}x${h} exceeds ${canvas}`);
  const ox = Math.floor((canvas - w) / 2);
  const oy = canvas - h - Math.floor(canvas / 16); // grounded near bottom, Gen 3 stage feel
  writePng(name, canvas, canvas, (set) => {
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const ch = row[x] ?? '.';
        if (ch === '.') continue;
        const c = palette[ch];
        if (!c) throw new Error(`${name}: no palette entry for "${ch}"`);
        set(ox + x, oy + y, c);
      }
    });
  }, prompt);
}

