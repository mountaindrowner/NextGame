type Palette = Record<string, [number, number, number, number]>;

const hex = (h: string, a = 255): [number, number, number, number] => [
  parseInt(h.slice(0, 2), 16),
  parseInt(h.slice(2, 4), 16),
  parseInt(h.slice(4, 6), 16),
  a,
];

