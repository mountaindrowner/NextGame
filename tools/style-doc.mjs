/**
 * Regenerates the reference-source appendix of docs/design/how-we-build-the-world.md:
 * everything after the APPENDIX:BEGIN marker is replaced with the current source
 * of the files that define the look, verbatim, so another AI can reproduce it.
 *   node tools/style-doc.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = new URL('..', import.meta.url).pathname;
const DOC = join(ROOT, 'docs/design/how-we-build-the-world.md');
const MARK = '<!-- APPENDIX:BEGIN';

/** [file, what it is, optional [firstLine, lastLine]] */
const FILES = [
  ['src/hd2d/noise.ts', 'Seeded RNG, value noise, fbm. Everything random goes through these.'],
  ['src/hd2d/geo.ts', 'Geometry with world-unit UVs; box/cyl/beam/prism helpers; cached materials.'],
  ['src/hd2d/textures.ts', 'The pixel texture system: Pix buffer, master palette, every material recipe, textTexture.'],
  ['src/hd2d/post.ts', 'Post-processing: tilt-shift and grade shaders, pass order.'],
  ['src/hd2d/mood.ts', 'Lighting presets and how a mood is applied (sun, hemisphere, fog, shadows).'],
  ['src/hd2d/world.ts', 'The tile world: glyph lookup, height, solids.'],
  ['src/hd2d/terrain.ts', 'The painted ground, aprons beyond the edges, water shader, grass.'],
  ['src/hd2d/field/props.ts', 'Foliage (blob crowns, cottonwood, mesquite, dead tree, bush), sway, power lines, truck, crates, tumbleweed, motes.'],
  ['src/hd2d/region1/section.ts', 'The section kit: glyph grid, region painter, edges, exits, height.'],
  ['src/hd2d/region1/props.ts', 'Region prop recipes (rock, sign, tank, bale, thread marks, husk, routines, crossing signal).', [1, 308]],
  ['src/hd2d/ohmstead/kit.ts', 'Underground kit: world-UV materials, LightPool (many lamps, few lights), wall lamps.', [1, 260]],
  ['src/hd2d/region1/interior.ts', 'Interiors: cutaway walls, wall textures, lamps.'],
  ['src/hd2d/doorway.ts', 'The door language: dressDoor and the promise check.'],
  ['src/hd2d/sprites.ts', 'Sprites: RotHero (8-direction billboards, sizing by measurement, packed sheets, mirror), blob shadow.'],
  ['src/hd2d/battle/themes.ts', 'Battle grounds per region (panels painted as local ground).'],
  ['src/hd2d/ui.ts', 'The pixel dissolve, name tag and travel card.', [1, 200]],
  ['tools/gen-ohms-style.mjs', 'PixelLab: 8-direction Ohms in the locked style (prompts included).'],
  ['tools/gen-cast-style.mjs', 'PixelLab: people in the locked style.'],
  ['tools/pack-anims.mjs', 'Packs animation frames into one sheet per animation.'],
];

const doc = readFileSync(DOC, 'utf8');
const at = doc.indexOf(MARK);
if (at < 0) throw new Error('appendix marker not found');
const sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT }).toString().trim();
let out = doc.slice(0, at) + `${MARK} (generated by tools/style-doc.mjs; do not edit below by hand) -->\n\n`;
out += `## Appendix: reference source (verbatim, from commit ${sha})\n\n`;
out += 'Port these first, unchanged; they are the ground truth for every number above. TypeScript on Three.js r170 (`three@^0.170.0`), built with Vite.\n\n';
for (const [f, what] of FILES) out += `- \`${f}\`: ${what}\n`;
out += '\n';
for (const [f, what, range] of FILES) {
  let src = readFileSync(join(ROOT, f), 'utf8').replace(/\s+$/, '');
  let note = '';
  if (range) {
    const lines = src.split('\n');
    src = lines.slice(range[0] - 1, range[1]).join('\n');
    note = ` (lines ${range[0]}–${Math.min(range[1], lines.length)} of ${lines.length})`;
  }
  const lang = f.endsWith('.mjs') ? 'js' : 'ts';
  out += `### ${f}\n\n${what}${note}\n\n\`\`\`${lang}\n${src}\n\`\`\`\n\n`;
}
writeFileSync(DOC, out.replace(/\n+$/, '\n'));
console.log(`appendix: ${FILES.length} files from ${sha}`);
